function q(value: string | number | boolean): string {
  return `'${String(value).replace(/'/g, "'\\''")}'`
}

function run(command: string): void {
  execSync(command, { stdio: "inherit" })
}

function asyncRun(command: string): Promise<void> {
  return new Promise((resolve, reject) => {
    const child = spawn("sh", ["-c", command], { stdio: "inherit" })
    child.on("close", (code) => {
      if (code === 0) resolve()
      else reject(new Error(`Process exited with code ${code}`))
    })
    child.on("error", reject)
  })
}

function hasTool(name: string): boolean {
  try {
    execFileSync("which", [name], { stdio: "ignore" })
    return true
  } catch {
    return false
  }
}

function _ensureTool(name: string): void {
  if (!hasTool(name)) {
    throw new Error(
      `Required tool '${name}' is not installed or not available in PATH.`
    )
  }
}

function resolveImageMagickCmd(): string {
  return hasTool("magick") ? "magick" : "convert"
}

function ensureDir(dirPath: string): void {
  mkdirSync(dirPath, { recursive: true })
}

function renderSvg(
  svgPath: string,
  pngPath: string,
  width: number,
  height: number
): void {
  execFileSync(
    "rsvg-convert",
    ["-w", String(width), "-h", String(height), "-o", pngPath, svgPath],
    {
      stdio: "inherit"
    }
  )
}

const imageMagickCmd = resolveImageMagickCmd()

function renderPaddedSvg(
  svgPath: string,
  pngPath: string,
  totalSize: number,
  artworkSize: number
): void {
  ensureDir(tmpDir)
  const tempPng = path.join(
    tmpDir,
    `temp-${path.basename(pngPath)}-${artworkSize}.png`
  )
  renderSvg(svgPath, tempPng, artworkSize, artworkSize)

  execFileSync(
    imageMagickCmd,
    [
      tempPng,
      "-background",
      "none",
      "-gravity",
      "center",
      "-extent",
      `${totalSize}x${totalSize}`,
      pngPath
    ],
    { stdio: "inherit" }
  )

  rmSync(tempPng, { force: true })
}

