// Generate extension icons for various sizes (16, 32, 48, 128)
function generateExtensionIcons(): void {
  const publicDir = path.join(rootDir, "public")
  const publicAssetsDir = path.join(publicDir, "assets")

  ensureDir(publicDir)
  ensureDir(publicAssetsDir)

  const iconTypes = [
    { name: "icon", svg: "icon.svg" },
    { name: "icon-dark", svg: "icon-dark.svg" },
    { name: "icon-light", svg: "icon-light.svg" }
  ]

  for (const { name, svg } of iconTypes) {
    const svgPath = path.join(assetsDir, svg)

    // Padded sizes for 16, 32, 48, 128 (artwork size is 75% of total size)
    for (const size of [16, 32, 48, 128]) {
      const outPublicAsset = path.join(publicAssetsDir, `${name}-${size}.png`)
      const artworkSize = Math.round(size * 0.75)
      renderPaddedSvg(svgPath, outPublicAsset, size, artworkSize)

      // Also generate in the root assets directory so they are present in the source folder
      const outRootAsset = path.join(assetsDir, `${name}-${size}.png`)
      renderPaddedSvg(svgPath, outRootAsset, size, artworkSize)
    }

    // Also copy / generate standard name.png at 128x128 padded (artwork size 96)
    const outPublicAssetStandard = path.join(publicAssetsDir, `${name}.png`)
    renderPaddedSvg(svgPath, outPublicAssetStandard, 128, 96)

    // And sync to the root assets directory
    const outRootAssetStandard = path.join(assetsDir, `${name}.png`)
    renderPaddedSvg(svgPath, outRootAssetStandard, 128, 96)
  }

  // Finally, the extension's root icon.png in public/ must be the 128x128 padded
  const outPublicRootIcon = path.join(publicDir, "icon.png")
  renderPaddedSvg(path.join(assetsDir, "icon.svg"), outPublicRootIcon, 128, 96)
}

