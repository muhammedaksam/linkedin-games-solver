// --- Locale Utility Helpers ---
interface LocaleMessage {
  message?: string
  description?: string
}

interface LocaleMessages {
  [key: string]: LocaleMessage | undefined
}

function readLocaleMessages(locale: string): LocaleMessages {
  const localeFile = path.join(localesDir, locale, "messages.json")
  if (!existsSync(localeFile)) {
    return {}
  }
  try {
    return JSON.parse(readFileSync(localeFile, "utf8")) as LocaleMessages
  } catch {
    return {}
  }
}

function getMessageValue(messages: LocaleMessages, key: string): string {
  const value = messages?.[key]?.message
  return typeof value === "string" ? value : ""
}

function cleanText(value: string): string {
  return value.replace(/\s+/g, " ").trim()
}

function truncateText(value: string, maxLength: number): string {
  if (value.length <= maxLength) {
    return value
  }
  return `${value.slice(0, Math.max(0, maxLength - 1)).trimEnd()}…`
}

// Maps locale base language to a representative Unicode codepoint in its script.
// Used alongside Latin U+0041 to find fonts that support BOTH Latin and the
// target script via fc-list, avoiding fallback Latin-only or script-only fonts.
const LOCALE_CHARSET: Record<string, string> = {
  am: "1200", // Ethiopic: ሀ U+1200
  ar: "0627",
  fa: "0627", // Arabic: ا U+0627
  bg: "0410",
  ru: "0410",
  sr: "0410",
  uk: "0410", // Cyrillic: А U+0410
  bn: "0985", // Bengali: অ U+0985
  el: "03B1", // Greek: α U+03B1
  gu: "0A85", // Gujarati: અ U+0A85
  he: "05D0", // Hebrew: א U+05D0
  hi: "0905",
  mr: "0905", // Devanagari: अ U+0905
  ja: "4E2D", // Japanese: 中 U+4E2D (CJK)
  kn: "0C85", // Kannada: ಅ U+0C85
  ko: "AC00", // Korean: 가 U+AC00
  ml: "0D05", // Malayalam: അ U+0D05
  ta: "0B85", // Tamil: அ U+0B85
  te: "0C05", // Telugu: అ U+0C05
  th: "0E01", // Thai: ก U+0E01
  zh: "4E2D" // Chinese: 中 U+4E2D (CJK)
}

function resolveFontPathForLocale(locale: string): string {
  const lang = locale.split("_")[0].toLowerCase()
  const scriptChar = LOCALE_CHARSET[lang]
  if (!scriptChar) {
    return ""
  }
  try {
    // Query fc-list for fonts that contain BOTH Latin 'A' (U+0041) and the
    // representative script character, ensuring the font supports both.
    const result = execFileSync(
      "fc-list",
      [`:charset=0041 ${scriptChar}`, "file"],
      { encoding: "utf8" }
    ).trim()
    if (!result) return ""

    // Take the first result, filtering out decorative/icon fonts
    for (const line of result.split("\n")) {
      const fontPath = line.split(":")[0].trim()
      if (
        fontPath &&
        existsSync(fontPath) &&
        !fontPath.includes("NerdFont") &&
        !fontPath.includes("Caskaydia")
      ) {
        return fontPath
      }
    }
    return ""
  } catch {
    return ""
  }
}

